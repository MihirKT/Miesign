logger = logging.getLogger(__name__)
IMAGE_WIDTH = 85 * mm
MAX_IMAGE_HEIGHT = 110 * mm
INK = colors.HexColor("#1f2a37")
RULE = colors.HexColor("#d5dbe3")
DISCLAIMER = ("Advisory estimate generated from one photo. Areas are approximate and rates are averages; "
              "confirm measurements and prices with your contractor before work begins.")
SIGNATURE = "Generated by Miesign &mdash; designed and built by Mihir Kapildev Tiwari."


def inr(amount):
    value = int(Decimal(str(abs(amount))).quantize(Decimal("1"), rounding=ROUND_HALF_UP))
    digits = str(value)
    if len(digits) > 3:
        head, tail = digits[:-3], digits[-3:]
        groups = []
        while len(head) > 2:
            groups.insert(0, head[-2:])
            head = head[:-2]
        if head:
            groups.insert(0, head)
        digits = ",".join(groups) + "," + tail
    return ("-" if amount < 0 and value else "") + "Rs " + digits


def _num(v):
    return f"{round(v, 1):g}"


def _esc(v):
    return escape(str(v))


def _image(path, styles):
    missing = Paragraph("No image", styles["Normal"])
    if not path or not os.path.isfile(path):
        logger.warning("Report image missing: %s", path)
        return missing
    try:
        img = Image(path)
        ratio = img.imageHeight / img.imageWidth
    except Exception:
        logger.warning("Report image unreadable: %s", path, exc_info=True)
        return missing
    height = min(IMAGE_WIDTH * ratio, MAX_IMAGE_HEIGHT)
    img.drawHeight = height
    img.drawWidth = height / ratio
    return img


def category_rows(lines):
    groups = {}
    for line in lines:
        groups.setdefault(line["category"], []).append(line)
    return [(cat, items, {"material": sum(i["material_cost"] for i in items),
                          "labor": sum(i["labor_cost"] for i in items),
                          "total": sum(i["total"] for i in items)})
            for cat, items in groups.items()]


def build_pdf(project_name, design_name, estimate, materials, original_path, render_path):
    styles = getSampleStyleSheet()
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm,
                            topMargin=15 * mm, bottomMargin=15 * mm, title=f"{project_name} - renovation estimate")
    loc = estimate.get("location") or {}
    where = ", ".join(v for v in (loc.get("city"), loc.get("state")) if v) or "Location not set"
    story = [
        Paragraph("Miesign &middot; exterior renovation estimate", styles["Title"]),
        Paragraph(f"Project: {_esc(project_name)} &middot; Design: {_esc(design_name)} &middot; {_esc(where)} &middot; "
                  f"{datetime.now(timezone.utc):%d %b %Y}", styles["Normal"]),
        Spacer(1, 6 * mm),
    ]
    if original_path or render_path:
        images = [[_image(p, styles) for p in (original_path, render_path)]]
        story += [Table([["Original", "Redesigned"]] + images, colWidths=[IMAGE_WIDTH + 4 * mm] * 2),
                  Spacer(1, 6 * mm)]

    story.append(Paragraph("Selected materials", styles["Heading2"]))
    story += [Paragraph(f"&bull; {_esc(m)}", styles["Normal"]) for m in materials] or [Paragraph("None", styles["Normal"])]
    story.append(Spacer(1, 4 * mm))

    story.append(Paragraph("Quantities and cost", styles["Heading2"]))
    rows = [["Item", "Area / length", "Quantity", "Rate (mat + lab)", "Material", "Labour", "Total"]]
    bold_rows = []
    for cat, items, tot in category_rows(estimate["lines"]):
        for line in items:
            rows.append([
                Paragraph(f"{_esc(line['name'])}<br/><font size=7>{_esc(', '.join(line['targets']))} &middot; "
                          f"{_esc(line['rate_source'])}</font>", styles["BodyText"]),
                f"{_num(line['measure'])} {line['rate_unit']}",
                f"{_num(line['quantity'])} {line['qty_unit']}",
                f"{line['material_rate']:g} + {line['labor_rate']:g} /{line['rate_unit']}",
                inr(line["material_cost"]), inr(line["labor_cost"]), inr(line["total"]),
            ])
        bold_rows.append(len(rows))
        rows.append([f"{cat} subtotal", "", "", "", inr(tot["material"]), inr(tot["labor"]), inr(tot["total"])])
    rows.append(["Grand total", "", "", "",
                 inr(sum(line["material_cost"] for line in estimate["lines"])),
                 inr(sum(line["labor_cost"] for line in estimate["lines"])), inr(estimate["grand_total"])])
    table = Table(rows, colWidths=[48 * mm, 22 * mm, 20 * mm, 28 * mm, 20 * mm, 20 * mm, 22 * mm], repeatRows=1)
    table.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
        ("LINEBELOW", (0, 0), (-1, 0), 1, INK),
        ("LINEBELOW", (0, 1), (-1, -2), 0.5, RULE),
        ("LINEABOVE", (0, -1), (-1, -1), 1, INK),
        ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ] + [("FONTNAME", (0, r), (-1, r), "Helvetica-Bold") for r in bold_rows]))
    story += [table, Spacer(1, 6 * mm), Paragraph("Assumptions", styles["Heading2"])]
    story += [Paragraph(f"&bull; {_esc(a)}", styles["Normal"]) for a in estimate["assumptions"] + estimate["warnings"]]
    story += [Spacer(1, 6 * mm), Paragraph(DISCLAIMER, styles["Italic"]),
              Paragraph(SIGNATURE, styles["Italic"])]
    doc.build(story)
    return buf.getvalue()


def for_design(design):
    project = Project.objects.get(id=design.project_id)
    photo = primary_photo(project)
    catalog = load_catalog()
    materials = [
        f"{catalog[a['material_id']]['name']} on {a['target'].partition(':')[2].replace('_', ' ')}"
        + (f" ({a['color']})" if a.get("color") else "")
        for a in design.spec.get("assignments", []) if a["material_id"] in catalog
    ]
    render_path = design.render_file.path if design.render_file else None
    return build_pdf(project.name, design.name, estimates.for_design(design), materials,
                     photo.file.path, render_path)
